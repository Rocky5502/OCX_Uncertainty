DATASET_ALIASES = {
    "repoexec": "RepoExec",
    "repo_exec": "RepoExec",
    "codereval": "CoderEval",
    "coder_eval": "CoderEval",
    "execrepobench": "ExecRepoBench",
    "execrepobench_data": "ExecRepoBench",
    "sample": "ExecRepoBench",
}


def _safe_float(value: Any) -> Optional[float]:
    if value in (None, "--", ""):
        return None
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    if math.isnan(out) or math.isinf(out):
        return None
    return out


def _read_summary(path: Optional[str], *, allow_offline: bool = False) -> Tuple[Dict[str, Tuple[float, float, float]], str]:
    if not path:
        return {}, "not provided"
    p = Path(path)
    data = json.loads(p.read_text(encoding="utf-8"))
    metadata = data.get("metadata", {})
    backend = str(metadata.get("backend") or "").lower()
    readiness = data.get("paper_readiness", "")
    if backend == "offline" and not allow_offline:
        return {}, f"offline summary omitted from final table: {path}"

    dataset = DATASET_ALIASES.get(str(metadata.get("dataset") or "").lower())
    if not dataset:
        return {}, f"unknown dataset in summary: {path}"

    row = next(
        (item for item in data.get("rq2_table", []) if item.get("method_key") == "with"),
        None,
    )
    if not row:
        return {}, f"missing OpenCoder RQ2 row: {path}"

    vals = []
    for metric in ("pass@1", "pass@3", "pass@5"):
        number = _safe_float(row.get(metric))
        vals.append(None if number is None else number * 100.0)
    if any(v is None for v in vals):
        return {}, f"incomplete pass@k values: {path}"
    return {dataset: tuple(vals)}, readiness or f"loaded {path}"


def _merged_rows(
    gpt_values: Dict[str, Tuple[float, float, float]],
    gemini_values: Dict[str, Tuple[float, float, float]],
) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for row in BASELINE_ROWS:
        item = {
            "approach": row["approach"],
            "group": row["group"],
            "values": dict(row.get("values", {})),
            "opencoder": row.get("opencoder"),
        }
        if row.get("opencoder") == "gpt":
            item["values"].update(gpt_values)
        elif row.get("opencoder") == "gemini":
            item["values"].update(gemini_values)
        rows.append(item)
    return rows


def _column_maxima(rows: List[Dict[str, Any]]) -> Dict[Tuple[str, int, str], float]:
    maxima: Dict[Tuple[str, int, str], float] = {}
    for group in ("GPT", "Gemini"):
        for dataset in DATASETS:
            for idx in range(3):
                values = []
                for row in rows:
                    if row["group"] != group:
                        continue
                    vals = row["values"].get(dataset)
                    if vals and vals[idx] is not None:
                        values.append(vals[idx])
                if values:
                    maxima[(group, idx, dataset)] = max(values)
    return maxima


def _fmt_cell(value: Optional[float], is_best: bool) -> str:
    if value is None:
        return "--"
    text = f"{value:.2f}"
    return rf"\textbf{{{text}}}" if is_best else text


def _latex_table(rows: List[Dict[str, Any]], caption: str, label: str) -> str:
    maxima = _column_maxima(rows)
    lines = [
        r"\begin{table*}[t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lccccccccc}",
        r"\toprule",
        r"\multirow{2}{*}{Approach} & \multicolumn{3}{c}{RepoExec} & \multicolumn{3}{c}{CoderEval} & \multicolumn{3}{c}{ExecRepoBench} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
        r"& Pass@1 & Pass@3 & Pass@5 & Pass@1 & Pass@3 & Pass@5 & Pass@1 & Pass@3 & Pass@5 \\",
        r"\midrule",
    ]
    previous_group = rows[0]["group"] if rows else ""
    for row in rows:
        if row["group"] != previous_group:
            lines.append(r"\midrule")
            previous_group = row["group"]
        cells = [row["approach"]]
        for dataset in DATASETS:
            vals = row["values"].get(dataset, (None, None, None))
            for idx, value in enumerate(vals):
                max_value = maxima.get((row["group"], idx, dataset))
                is_best = value is not None and max_value is not None and abs(value - max_value) < 1e-9
                cells.append(_fmt_cell(value, is_best))
        lines.append(" & ".join(cells) + r" \\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}%",
        r"}",
        r"\end{table*}",
        "",
    ])
    return "\n".join(lines)


def _markdown_table(rows: List[Dict[str, Any]]) -> str:
    header = ["Approach"]
    for dataset in DATASETS:
        for metric in METRICS:
            header.append(f"{dataset} {metric}")
    lines = [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(["---"] + ["---:"] * 9) + " |",
    ]
    for row in rows:
        cells = [row["approach"].replace(r"$_{\mathrm{", "_").replace(r"}}$", "")]
        for dataset in DATASETS:
            vals = row["values"].get(dataset, (None, None, None))
            for value in vals:
                cells.append("--" if value is None else f"{value:.2f}")
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _status_block(gpt_status: str, gemini_status: str, allow_offline: bool) -> str:
    return "\n".join([
        "% OpenCoder result status",
        rf"% GPT summary: {gpt_status}",
        rf"% Gemini summary: {gemini_status}",
        rf"% Offline summaries allowed in table: {str(allow_offline).lower()}",
        "% Use this table in RQ2, not RQ1. RQ1 is for source influence/uncertainty analysis.",
        "",
    ])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gpt-summary", default=None)
    ap.add_argument("--gemini-summary", default=None)
    ap.add_argument("--out-dir", default="results/overleaf")
    ap.add_argument("--allow-offline", action="store_true")
    args = ap.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    gpt_values, gpt_status = _read_summary(args.gpt_summary, allow_offline=args.allow_offline)
    gemini_values, gemini_status = _read_summary(args.gemini_summary, allow_offline=args.allow_offline)
    rows = _merged_rows(gpt_values, gemini_values)

    caption = (
        "Performance comparison of different approaches with various LLMs "
        "(best performance in bold)."
    )
    label = "tab:opencoder_llm_comparison"
    latex = _status_block(gpt_status, gemini_status, args.allow_offline) + _latex_table(rows, caption, label)
    markdown = "\n".join([
        "# OpenCoder LLM Comparison Results",
        "",
        f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
        "",
        "Recommended paper placement: RQ2, because this table evaluates the robustness/effectiveness of OpenCoder across LLM backends. Keep RQ1 for retrieved-source influence: API knowledge, context code, and similar-code uncertainty effects.",
        "",
        f"GPT status: {gpt_status}",
        f"Gemini status: {gemini_status}",
        "",
        _markdown_table(rows),
        "",
    ])

    (out_dir / "opencoder_llm_comparison_table.tex").write_text(latex, encoding="utf-8")
    (out_dir / "opencoder_llm_comparison_table.md").write_text(markdown, encoding="utf-8")
    (out_dir / "opencoder_results_for_overleaf.tex").write_text(
        "\n".join([
            "% Auto-generated OpenCoder result snippets for Overleaf.",
            "% Requires: \\usepackage{booktabs,multirow,graphicx}",
            "",
            latex,
            "",
            "% Recommended section note:",
            "% Place Table~\\ref{tab:opencoder_llm_comparison} under RQ2.",
            "% Use source-ablation tables/figures under RQ1.",
            "",
        ]),
        encoding="utf-8",
    )
    print(f"Wrote Overleaf result files to {out_dir}")


if __name__ == "__main__":
    main()
